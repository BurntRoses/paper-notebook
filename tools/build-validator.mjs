import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Ship the schema checks, rather than compiling the schema in every reader.
const schema = JSON.parse(await readFile(new URL('../schemas/notebook.schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv({ allErrors: true, strict: false, inlineRefs: false, loopRequired: 1, loopEnum: 1, code: { source: true } });
const bundled = await build({
  stdin: { contents: standaloneCode(ajv, ajv.compile(schema)), sourcefile: 'notebook-validator.cjs', resolveDir: fileURLToPath(new URL('../', import.meta.url)) },
  absWorkingDir: fileURLToPath(new URL('../', import.meta.url)),
  // Minification also removes CommonJS debug keys containing the dependency's
  // physical path, so shared/symlinked installs produce the same checked file.
  bundle: true, minify: true, format: 'esm', platform: 'browser', target: 'es2022', write: false,
});
const source = '// Generated by tools/build-validator.mjs from schemas/notebook.schema.json.\n' + bundled.outputFiles[0].text;
const target = new URL('../src/model/notebook-validator.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== source) throw new Error(`Stale validator: run node ${fileURLToPath(import.meta.url)}`);
} else {
  await writeFile(target, source);
}
